-- --------------------------------------------------------------------------- #
-- 098 三张运行时懒建表收编（weak_knowledge / answer_review_queue / conflict_review_queue）
-- --------------------------------------------------------------------------- #
-- 背景（2026-10-15）
-- ----------------------
-- 这三张表此前**不在任何 schema 分片里**，只在服务启动/调用时用 SQLite 风格的
-- DDL 懒建（`services/qa_foundation._QA_DDL` 与 `services/confidence_service._CONFLICT_DDL`，
-- 都是 `INTEGER PRIMARY KEY AUTOINCREMENT` + TEXT 时间戳）。
--
-- 后果（实测）：PG 上这些 CREATE 全部失败，而 `ensure_qa_schema` 又用
-- `except Exception: pass` 把异常吞掉 —— 于是**两张库都没有表**，
-- 链路一跑到就 `relation "xxx" does not exist`（测试侧 33 例失败；
-- 生产侧则是弱项统计/复核队列功能整体不可用）。
--
-- 这正是项目记忆里"静默 except 是最贵的 bug"的又一次复现。
-- 本分片把三张表按 PG 正典写法收进 schema 主入口（时间戳用 TIMESTAMPTZ，
-- 自增用 GENERATED BY DEFAULT AS IDENTITY），两边库同时具备；
-- 服务侧懒建保留为兜底（IF NOT EXISTS 命中即无副作用）。
--
-- 幂等：CREATE TABLE IF NOT EXISTS，可反复重跑。排序列末（紧随 097）。
-- --------------------------------------------------------------------------- #

-- 1) 弱项知识点统计（services/qa_foundation）
CREATE TABLE IF NOT EXISTS weak_knowledge (
    id            INTEGER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    knowledge_point TEXT NOT NULL,
    subject       VARCHAR(50),
    wrong_count   INTEGER DEFAULT 0,
    total_count   INTEGER DEFAULT 0,
    accuracy      REAL,
    mastery       REAL,
    last_wrong_at TIMESTAMPTZ,
    updated_at    TIMESTAMPTZ,
    CONSTRAINT uq_weak_knowledge_kp_subject UNIQUE (knowledge_point, subject)
);

COMMENT ON TABLE weak_knowledge IS '弱项知识点统计（按知识点×科目聚合错题/正确率）';

-- 2) 答案复核队列（services/qa_foundation）
CREATE TABLE IF NOT EXISTS answer_review_queue (
    id            INTEGER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    question_id   INTEGER,
    conflict_type VARCHAR(50),
    detail        TEXT,
    status        VARCHAR(20) DEFAULT 'pending',
    resolution    TEXT,
    created_at    TIMESTAMPTZ,
    CONSTRAINT uq_answer_review_qid_type UNIQUE (question_id, conflict_type)
);

COMMENT ON TABLE answer_review_queue IS '答案待复核队列（低置信/冲突答案）';
CREATE INDEX IF NOT EXISTS idx_answer_review_status ON answer_review_queue (status);

-- 3) 冲突裁决队列（services/confidence_service）
CREATE TABLE IF NOT EXISTS conflict_review_queue (
    id              INTEGER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    question_id     INTEGER NOT NULL,
    answer_a        TEXT NOT NULL DEFAULT '',
    answer_b        TEXT NOT NULL DEFAULT '',
    source_a        TEXT NOT NULL DEFAULT '',
    source_b        TEXT NOT NULL DEFAULT '',
    confidence_a    REAL NOT NULL DEFAULT 0.0,
    confidence_b    REAL NOT NULL DEFAULT 0.0,
    suggested_winner TEXT,
    status          VARCHAR(20) NOT NULL DEFAULT 'open',
    resolution      TEXT,
    reviewer_note   TEXT,
    reviewed_at     TIMESTAMPTZ,
    created_at      TIMESTAMPTZ NOT NULL DEFAULT now()
);

COMMENT ON TABLE conflict_review_queue IS '答案冲突裁决队列（同题多源答案不一致）';

-- 同题只允许一条 open 冲突（部分唯一索引，SQLite 与 PG 均支持）
CREATE UNIQUE INDEX IF NOT EXISTS uq_conflict_open
    ON conflict_review_queue (question_id) WHERE status = 'open';
CREATE INDEX IF NOT EXISTS idx_conflict_status
    ON conflict_review_queue (status);
