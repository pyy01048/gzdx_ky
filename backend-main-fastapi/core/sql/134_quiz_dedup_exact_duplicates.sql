-- 134_quiz_dedup_exact_duplicates.sql
-- 题库去重：隔离活跃池中「内容 + 选项 + 答案」完全一致的真重复题，每组保留最小 ID 副本。
--
-- 依据（云端只读审计，2025-xx）：
--   对 11251 条活跃题按归一化内容分组，排除已知误报（作文占位题「写作（第N题）」、
--   阅读子题共用题干「新题型（partb）第N题」、通用题干 "which of the following..."），
--   再要求组内成员选项文本与答案完全一致，得到 15 组真重复、17 条冗余行。
--   用户历史引用核查：error_records=0、exam_answers=0（其余引用表均为 SET NULL/CASCADE，
--   且本表为软隔离不物理删除，无副作用）。
--
-- 处理口径（与 131/133 一致，幂等）：
--   is_available=false / is_junk=true（移出练习池，仍可检索）
--   needs_review=false（真重复为自动判定，无需进入人工复核队列）
--   validation_status='warn' / validation_errors 追加 duplicate_content 原因
-- 不编造数据、不物理删除；保留最小 ID 副本以维持历史关联稳定。

UPDATE quiz_questions
SET is_available = false,
    is_junk = true,
    needs_review = false,
    validation_status = 'warn',
    validation_errors = coalesce(validation_errors, '[]'::jsonb)
      || '[{"code":"duplicate_content","detail":"与同池题目内容/选项/答案完全一致，已移出练习池（保留最小 ID 副本）"}]'::jsonb,
    validated_at = now(),
    updated_at = now()
WHERE id IN (
    -- 每组保留最小 ID，隔离其余
    59, 101,    -- 组 [42,59,101]   仪表放大电路…
    50,         -- 组 [15,50]       某放大电路负载开路…
    52,         -- 组 [35,52]       和 TTL 相比 CMOS…
    62, 106,    -- 组 [16,62,106]   两个放大倍数相同…
    67,         -- 组 [17,67]       测量放大器输出电阻…
    72,         -- 组 [44,72]       引入负反馈…
    107,        -- 组 [63,107]      二极管正向电压…
    111,        -- 组 [71,111]      乙类 OCL 互补对称…
    251,        -- 组 [223,251]     适合传递函数描述…
    21186,      -- 组 [19474,21186] 散列冲突…
    33497,      -- 组 [18637,33497] V 操作唤醒进程…
    33595,      -- 组 [18810,33595] LRU 页面置换…
    33604,      -- 组 [18824,33604] 32 位实地址 48 位虚拟…
    33621,      -- 组 [18872,33621] 文件相对路径名…
    33630       -- 组 [18889,33630] 文件 3 个记录…
)
AND is_available IS TRUE;
