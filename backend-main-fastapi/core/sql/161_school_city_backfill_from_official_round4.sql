-- 院校城市回填第四批（2026-11-24）：对上批仍缺城市的 48 所（有官网）逐站复抓，
-- 仅回填官网原文明确写出城市名的 5 条；证据逐条留痕：
-- backfill_local/out/school_city_161_evidence.csv（含页面 URL / 抓取日期 / 原文片段）。
--
-- 本轮排除说明（不猜、不编造）：
--   #158 山西农业大学：页脚并列「太原龙城校区 / 太谷校区」，多校区不取单城；
--   #163/#209/#212/#551/#569/#608/#632/#695/#715/#774/#795：站点从云端不可达（连接超时/SSL），无原文；
--   #264 机械总院哈尔滨焊接所：命中页为机械总院总部地址（北京），非本所；
--   #634 广西艺术学院：命中页为通知中的百色考点地址，非办学地；
--   #700 贵州师范大学：页脚地址为「贵安新区」，非城市名（校歌中的雪涯路属历史表述，不采）；
--   #767 陕西中医药大学：地址为「西咸新区」，非城市名；
--   #729 西藏民族大学：咸阳属实但与 province=西藏 并列易误读，维持空白待人工定夺。
--
-- 守卫：仅回填 city 为空白的记录，重复执行不会覆盖既有城市。

UPDATE kaoyan_schools AS s
SET city = v.city,
    updated_at = now()
FROM (VALUES
    (134, '保定'),   -- 研招网单位名称：华北电力大学(保定)；所在地：河北省
    (402, '六安'),   -- 地址：安徽省六安市云露桥西月亮岛
    (452, '南昌'),   -- 江西科技师范大学位于……江西省南昌市
    (580, '长沙'),   -- 地址：长沙市岳麓区枫林三路1015号
    (612, '广州')    -- 学校现有广州和佛山两个校区……广州校区地处琶洲
) AS v(id, city)
WHERE s.id = v.id
  AND (s.city IS NULL OR btrim(s.city) = '');
