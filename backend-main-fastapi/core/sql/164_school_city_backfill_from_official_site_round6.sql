    (700, '贵阳'),      -- 研究生院官网页脚：地址 贵州省贵阳市贵安新区大学城栋青路
    (801, '西宁'),      -- 官网页脚：青海省西宁市城东区八一中路3号
    (815, '乌鲁木齐')   -- 官网页脚：新疆乌鲁木齐市北京中路449号
) AS v(id, city)
WHERE s.id = v.id
  AND (s.city IS NULL OR btrim(s.city) = '');
