    (443, '南昌'),      -- 研究生院官网：地址 江西省南昌市新建区梅岭大道1688号
    (579, '长沙'),      -- 官网页脚：主校区 湖南省长沙市湘江新区枫林二路139号（雷锋校区同城）
    (628, '南宁'),      -- 官网页脚：仙葫校区/明秀校区均「广西南宁市」
    (634, '南宁'),      -- 招生办官网：地址 广西南宁市教育路7号
