SET city = v.city,
    updated_at = now()
FROM (VALUES
    (140, '石家庄'),    -- 官网页脚：河北省石家庄市中山东路361号
    (141, '石家庄'),    -- 官网联系方式：裕华校区/红旗校区均「河北省石家庄市」
