-- 院校城市回填（2026-11-24，第六批）：第五批（163）跑完研招网简介后仍缺 city 的 97 所中，
-- 对 30 所有官网的院校抓「学校简介/概况/联系我们/研究生院」页面原文（本地只读抓取，带页面 URL），
-- 只回填页面明确写出城市名的 12 条。其余仍留空（见排除说明）。
--
-- 主校区口径（沿用 163，未放宽）：
--   1) 页面写「校本部/主校区/本部」+ 城市 → 取该城市；
--   2) 并列多城市校区且无主校区字样 → 不取（本轮 165/184/380）；
--   3) 「省+市」「地址：…市」原文直书 → 视为明确办学地；
--   4) 城市与库内 province 反查冲突 → 不取（本轮 729）；
--   5) 不按校名推测；不取「新区/大学城/街道名」当城市（如 700 只认原文「贵阳市」）；
--   6) 同城两校区（如 141 裕华/红旗、628 仙葫/明秀、579 主校区/雷锋校区）视为单城市。
--
-- 证据逐条留痕（id / 院校 / 城市 / 状态 / URL / 原文短语）：
--   backfill_local/out/school_city_164_evidence.csv
-- 抓取与判定脚本：backfill_local/scrape_city_from_official_164.py
--
-- 本轮排除（写清原因，避免下轮重复调研）：
--   #165 山西中医药大学：官网并列为「晋中校区」「太原校区」，无主校区表述；
--   #184 辽宁大学：官网「三个校区，即沈阳崇山校区、沈阳蒲河校区和辽阳武圣校区」，无主次标记；
--   #380 浙江传媒学院：官网校址并列「杭州钱塘校区」「桐乡乌镇校区」，无主次标记；
--   #729 西藏民族大学：官网「西安、咸阳两个校区，并在拉萨建有教学实践基地」，
--        拉萨是实践基地不是校区，且与库内 province=西藏 冲突，维持空白；
--   #158 前的 #163 山西大同大学、#212 中国医科大学、#375 中国美术学院等 13 所：
--        官网可抓页面未写城市，或站点拒绝抓取（空响应），按「不猜」留空；
--   其余 65 所科研院所无官网（中国航空/兵器/航天下属所），研招网简介亦无城市，留空。
--
-- 守卫：仅回填 city 为空白的记录，重复执行不会覆盖既有城市；不物理删除。

