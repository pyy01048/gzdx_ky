# -*- coding: utf-8 -*-
"""DDL 双底座兼容：把 SQLite 专用建表语法转成当前数据库可执行的写法。

问题（2026-10 实测）
--------------------
项目自称「SQLite WAL + 可选 PostgreSQL」双底座，但**运行期建表 SQL 全是
SQLite 专用语法**，散落在 10 个服务的 `_SCHEMA_SQL` 常量里，共 26 处：

    CREATE TABLE IF NOT EXISTS answer_cache (
        id INTEGER PRIMARY KEY AUTOINCREMENT,   ← SQLite 专用
        ...
    )

当 `DATABASE_URL` 指向 PostgreSQL 时（本机 127.0.0.1/kaoyan），执行这段 SQL
直接抛 `psycopg.errors.SyntaxError: syntax error at or near "AUTOINCREMENT"`，
导致测试 setup 全部 error（实测 12 个 error）。

两种后端的正确写法
------------------
    SQLite      id INTEGER PRIMARY KEY AUTOINCREMENT
    PostgreSQL  id INTEGER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY
                （早期版本用 SERIAL，IDENTITY 是 SQL:2003 标准写法，PG 10+ 支持）

本模块提供 `adapt_ddl(sql)`，按当前连接的方言做文本替换，**调用方无需改 SQL**。

用法：
    from services.ddl_compat import adapt_ddl
    conn.executescript(adapt_ddl(_SCHEMA_SQL))

判据：用连接对象自身判断方言（sqlite3.Connection → sqlite；psycopg → pg），
不依赖全局配置，避免「测试里连 PG 但配置说 SQLite」的错配。
"""
from __future__ import annotations

import re

__all__ = ["adapt_ddl", "is_sqlite", "is_postgres"]

#: SQLite 自增主键写法（含大小写与多余空白）
_SQLITE_AUTOINC_RE = re.compile(
    r"INTEGER\s+PRIMARY\s+KEY\s+AUTOINCREMENT", re.I
)
#: 反过来的 PG 写法（供需要还原时用）
_PG_IDENTITY_RE = re.compile(
    r"INTEGER\s+GENERATED\s+BY\s+DEFAULT\s+AS\s+IDENTITY\s+PRIMARY\s+KEY", re.I
)


def _driver_module(conn) -> str:
    """取连接**底层驱动**的模块名。

    关键（实测踩坑）：从 SQLAlchemy 拿到的是连接池代理
    （``sqlalchemy.pool.base._ConnectionFairy``），不是真实驱动连接。
    直接看 ``type(conn).__module__`` 会得到 ``sqlalchemy.pool.base``，
    于是既不是 sqlite 也不是 psycopg，方言判断全部失效、DDL 不做转换、
    在 PG 上继续抛 AUTOINCREMENT 语法错误。

    因此必须穿透代理链取真实连接：``conn.driver_connection``（SQLAlchemy 1.4+）
    或 ``conn.connection``（DBAPI 连接）。
    """
    cur = conn
    # 最多穿透 4 层，防环
    for _ in range(4):
        if cur is None:
            break
        mod = type(cur).__module__.split(".")[0]
        if mod in ("sqlite3", "psycopg", "psycopg2"):
            return mod
        nxt = getattr(cur, "driver_connection", None) or getattr(cur, "connection", None)
        if nxt is None or nxt is cur:
            break
        cur = nxt
    return type(conn).__module__.split(".")[0]


def is_sqlite(conn) -> bool:
    """连接是否为 SQLite（会穿透 SQLAlchemy 连接池代理）。"""
    return _driver_module(conn) == "sqlite3"


def is_postgres(conn) -> bool:
    """连接是否为 PostgreSQL（psycopg2 / psycopg3）。"""
    return _driver_module(conn) in ("psycopg", "psycopg2")


def adapt_ddl(sql: str, conn=None) -> str:
    """把 DDL 适配到 conn 所连数据库的方言。

    Args:
        sql: 原始建表语句（历史代码按 SQLite 编写）。
        conn: 数据库连接。为 None 时按 SQLite 处理（向后兼容旧调用）。

    Returns:
        可在该连接上执行的 SQL。
    """
    if conn is None or is_sqlite(conn):
        return sql

    if is_postgres(conn):
        # AUTOINCREMENT → GENERATED BY DEFAULT AS IDENTITY（放在 PRIMARY KEY 前）
        sql = _SQLITE_AUTOINC_RE.sub(
            "INTEGER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY", sql
        )
        # SQLite 的 DATETIME 在 PG 里应落到 TIMESTAMP。
        # 负向lookahead排除函数调用：``datetime('now')`` 是**函数调用**不是类型，
        # 这里若一并替换会产出非法的 ``TIMESTAMP('now')``（adapt_sql 对所有
        # 语句都跑 DDL 改写，实测踩到）。
        sql = re.sub(r"\bDATETIME\b(?!\s*\()", "TIMESTAMP", sql, flags=re.I)
        # 去掉 SQLite 专属 PRAGMA（PG 无此概念）
        sql = re.sub(r"^\s*PRAGMA\s+[^;]+;", "", sql, flags=re.I | re.M)
        return sql

    # 未知方言：原样返回，让上层报错时能看到原始 SQL 便于定位
    return sql


def adapt_ddl_sqlite_to_pg(sql: str) -> str:
    """纯文本转换（不知道连接对象时使用）。"""
    sql = _SQLITE_AUTOINC_RE.sub(
        "INTEGER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY", sql
    )
    sql = re.sub(r"\bDATETIME\b(?!\s*\()", "TIMESTAMP", sql, flags=re.I)
    return re.sub(r"^\s*PRAGMA\s+[^;]+;", "", sql, flags=re.I | re.M)
