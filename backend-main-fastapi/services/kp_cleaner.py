def _kw_score(text: str, keywords: list[str]) -> int:
    """关键词命中打分（长关键词权重更高，避免'门电路'被'电路'抢占）。"""
    t = text or ""
    score = 0
    for kw in keywords:
        if kw in t:
            score += max(1, len(kw) // 2)
    return score


def map_chapter(
    name: str,
    chapter: str | None,
    subject: str | None,
    content: str | None = None,
    *,
    min_score: int = 2,
) -> str | None:
    """把知识点归位到标准章节。

    依次尝试（置信度从高到低）：
      1. 现有 chapter 字段已是标准章名 → 直接用
      2. 现有 chapter 里的章号 → 对齐大纲同章号
      3. 知识点名 + 章节名 + 来源正文 的关键词打分 → 取最高分章
    都不确定则返回 None（**宁可空着，也不塞错误章节**）。
    """
    std = taxonomy.normalize_subject(subject)
    outline = taxonomy.chapters_of(std)
    if not outline:
        return None

    # 1/2. 现有 chapter
    ch = (chapter or "").strip()
    if ch in outline:
        return ch
    if ch:
        m = re.search(r"第\s*([0-9]{1,2}|[一二三四五六七八九十]+)\s*章", ch)
        if m:
            num = m.group(1)
            for o in outline:
                om = re.search(r"第\s*([0-9]{1,2}|[一二三四五六七八九十]+)\s*章", o)
                if om and om.group(1) == num:
                    return o

    # 3. 关键词打分
    kws = CHAPTER_KEYWORDS
    if not kws:
        return None
    # 知识点名权重最高（×3），章节字段次之（×2），正文只给少量（×1，且截断）
    haystack_name = name or ""
    haystack_ch = ch
    haystack_body = (content or "")[:2000]

    scored: list[tuple[int, str]] = []
    for o in outline:
        words = kws.get(o)
        if not words:
            continue
        s = (_kw_score(haystack_name, words) * 3
             + _kw_score(haystack_ch, words) * 2
             + _kw_score(haystack_body, words))
        if s > 0:
            scored.append((s, o))

    if not scored:
        return None
    scored.sort(key=lambda x: -x[0])
    best_score, best = scored[0]

    if best_score < min_score:
        return None

    # 模糊则拒绝：与冠军得分接近（> 60%）的**其他章**存在时，说明证据不足以区分，
    # 返回 None，避免挂到错误的章。
    # 实例："集成运放构成反相比例放大器时，反馈类型为" 里
    # 第4章(集成运放) 与 第6章(反馈) 都在响应，硬取最高分会挂到"集成运算放大电路"，
    # 而考纲把"反馈的判断方法"归在第6章 —— 这种情况判为不确定更诚实。
    if len(scored) > 1:
        runner_up = scored[1][0]
        if runner_up > best_score * 0.6:
            return None

    return best
