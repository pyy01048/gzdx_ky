"""知识点清洗：筛掉自动抽取产生的垃圾条目，并归位到标准章节。

### 为什么需要这个模块

实测存量 898 条 knowledge_points，`chapter` 字段里存的根本不是章节名，
而是**文件名 / 考卷名 / 残句**："《数字电路》考研复习参考共383页"、
"2004年真题逐题细解"、"系是"逢二进一""、"下页总目录推出下页"。

`name` 字段同样是抽取残留：整页幻灯片标题拼接、OCR 断句残片、
甚至 "11010010 11010011返回上页[例1" 这种纯噪声。

拿这种数据做"章节→知识点→题型"三级结构和复习进度追踪，
统计出来的进度全是假的。所以必须先清洗，再谈结构化。

### 两个可复用的判定

- `assess_knowledge_point(name, subject)` → 质量判定，给出 is_valid 与原因
- `map_chapter(name, chapter, subject, content)` → 把任意来源信息归位到标准章节
"""

from __future__ import annotations

import re

from services import taxonomy

# --------------------------------------------------------------------------- #
# 一、垃圾知识点识别
# --------------------------------------------------------------------------- #

# 页面/课件导航残留（PDF 导出 PPT 时的固定噪声）
_NAV_NOISE = [
    "下页", "上页", "返回", "总目录", "推出下页", "目录", "单击此处",
    "单击添加", "标题文字", "PowerPoint", "微软用户", "版权所有",
    "单击编辑", "在此输入", "样例文本", "LOGO", "logo",
]

# OCR / 抽取残片特征
_OCR_NOISE = [
    "•••", "···", "fl ", "fl]", "Section I", "Section fl",
    "兄套外教", "音濒",
]

# 知识点名的合理长度区间
_NAME_MIN = 2
_NAME_MAX = 40


def assess_knowledge_point(name: str, subject: str | None = None) -> dict:
    """判定一条知识点是否可用。

    返回 {is_valid: bool, reason: str|None, score: int}
    score 越高越可信（0-100）。
    """
    n = (name or "").strip()
    reasons: list[str] = []

    if not n:
        return {"is_valid": False, "reason": "空名称", "score": 0}

    if len(n) < _NAME_MIN:
        reasons.append("名称过短")

    if len(n) > _NAME_MAX:
        reasons.append(f"名称过长({len(n)}字)，疑似整段正文")

    # 导航噪声
    for kw in _NAV_NOISE:
        if kw in n:
            reasons.append(f"含页面导航词「{kw}」")
            break

    for kw in _OCR_NOISE:
        if kw in n:
            reasons.append(f"含OCR残片「{kw}」")
            break

    # 纯数字/符号：OCR 乱码
    if re.fullmatch(r"[\d\s\.\-\[\]\(\)（）【】、,，:：;；%]+", n):
        reasons.append("纯数字符号，OCR乱码")

    # 无中文且非英文单词形态
    has_cn = bool(re.search(r"[\u4e00-\u9fa5]", n))
    if not has_cn:
        # 英文条目：必须是像术语的形态（首字母大写或全大写，长度 3-30，无破碎空格）
        if not re.fullmatch(r"[A-Za-z][A-Za-z\-\s'’]{2,29}", n):
            reasons.append("非中文且不像英文术语")
        elif re.search(r"[a-z]{2,}[A-Z]", n):
            reasons.append("英文断词错乱（如 ofthe）")

    # 中文但以虚词/连接词结尾，多为断句残片
    if has_cn and re.search(r"[的了和与是在有对为及这那请用，。、；：]$", n):
        reasons.append("以虚词/标点结尾，疑似断句残片")

    # 句读过多 → 是正文不是概念名（必须含全角标点，中文文本里多的是全角）
    punct = len(re.findall(r"[，。；：、,.;:！？!?]", n))
    if punct >= 3:
        reasons.append("标点过多，疑似正文片段")

    # 比较句 / 判断句的尾缀 → 断句残片，不是概念名
    if has_cn and re.search(r"(要高得多|要低得多|要大得多|要小得多|得多|不可|不能正常工作)$", n):
        reasons.append("比较句/判断句尾缀，疑似断句残片")

    # 陈述句特征（"…是…"、"…的…" 长句）
    if has_cn and len(n) > 20 and re.search(r"(是|有|为|表示|称为|叫做)", n) and punct >= 1:
        reasons.append("陈述句形态，非概念名")

    # 章节标题残留：以"第X节/一、"开头且过长
    if re.match(r"^\s*(第\s*[0-9一二三四五六七八九十]+\s*[章节]|[一二三四五六七八九十]+[、.])", n) and len(n) > 12:
        reasons.append("含章节编号前缀且过长，疑似幻灯片标题")

    score = 100 - 20 * len(reasons)
    # 明确是标准章节名的，加分
    std = taxonomy.normalize_subject(subject)
    if n in taxonomy.chapters_of(std):
        score = min(100, score + 10)

    return {
        "is_valid": not reasons,
        "reason": "；".join(reasons) if reasons else None,
        "score": max(0, score),
    }


