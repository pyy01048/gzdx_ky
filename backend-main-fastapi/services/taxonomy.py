# 章标题识别（供 structure_parser 使用）
# --------------------------------------------------------------------------- #
# 注意：**不能**用宽松的 ^\d{1,2}\.\s*... 当章模式 ——
# 那样 "1.1 几种常用的数制" 这种小节号会被当成章标题（它会匹配到 "1." 开头），
# 导致章节点被小节污染、甚至整篇识别失败。章模式只认"第N章"/"Chapter N"，
# 以及不带点号的裸编号。
CHAPTER_PATTERNS = [
    r"^\s*第\s*[0-9一二三四五六七八九十]+\s*章\s*[^\n]{0,40}$",
    r"^\s*Chapter\s*\d+[^\n]{0,40}$",
    r"^\s*[0-9]{1,2}\s+[^\n]{2,40}$",              # "1 逻辑代数基础"（必须有空格）
    r"^[0-9]{1,2}\s*[、．]\s*[^\n]{2,40}$",         # "1、逻辑代数基础"
]

SECTION_PATTERNS = [
    r"^\s*第\s*[0-9一二三四五六七八九十]+\s*节\s*[^\n]{0,40}$",
    r"^\s*[0-9]{1,2}\.[0-9]{1,2}\s*[^\n]{2,40}$",  # "1.1 数制"
    r"^\s*[一二三四五六七八九十]+[、.]\s*[^\n]{2,40}$",
]
