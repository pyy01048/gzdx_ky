# 已配置科目名缓存（由 load_configured_subjects 从 subject_config 表装载）。
# normalize_subject 据此把"已配置科目（含自定义）"原样保留，不归一到内置池。
_CONFIGURED_SUBJECTS: set[str] = set()


def load_configured_subjects(db) -> set[str]:
    """从 subject_config 表装载全部科目名到内存缓存。

    管理接口（POST/PUT/DELETE）每次写库后应调用本函数刷新缓存，
    使后续 normalize_subject 能立刻识别新配置的自定义科目名。
    """
    from models import SubjectConfig

    names = {row[0] for row in db.query(SubjectConfig.subject).all() if row[0]}
    _CONFIGURED_SUBJECTS.clear()
    _CONFIGURED_SUBJECTS.update(names)
    return names


def is_configured_subject(db, subject: str | None) -> bool:
    """该科目名是否已在 subject_config 中配置过（内置默认或用户自定义）。"""
    from models import SubjectConfig

    s = (subject or "").strip()
    if not s:
        return False
    return db.query(SubjectConfig).filter(SubjectConfig.subject == s).first() is not None


