"""文档学科锁白名单（leaf-level 真学科）。

为什么需要独立白名单
--------------------
`services/taxonomy.py` 的 `ALL_SUBJECTS` 是「知识点可挂载标签」的**全集**，
它同时包含两类不同层级的东西：

  * **考研招生/考试科目口径下的独立学科**（可作为文档归属标签）
  * **408 内部的二级学科**（`数据结构` / `操作系统` / `计算机网络` / `软件工程`）
    以及一级学科名（`计算机科学与技术` / `电子信息` / `电气工程` …）

文档学科锁（`kp_extract.resolve_subject`）决定**整篇文档的知识点归属**。
如果直接拿 `ALL_SUBJECTS` 当白名单，一篇 408 真题 PDF 会被标成
`数据结构` 而不是 `计算机学科专业基础408` —— 同层级值互相污染。

本模块只收**叶子级真学科**：判断标准是「考研招生/考试科目口径下是否是
一门独立学科」。408 内部考的正是那四门二级学科，但作为**文档归属标签**
它应该归到 `计算机学科专业基础408`。

⚠️ 本模块**不修改** `taxonomy.CORE_SUBJECTS`，只做叠加式收敛。
"""

from typing import FrozenSet

#: 公共课（统考科目口径）
_PUBLIC_SUBJECTS = frozenset({"政治", "英语", "数学"})

#: 408 统考专业课 —— 二级学科（数据结构/操作系统/计算机网络/软件工程）
#: **故意不在**本白名单内，它们是 408 的内部组成，不是独立招生学科。
_INTEGRATED_408 = "计算机学科专业基础408"

#: 专业课 / 支撑科目（叶子级真学科）
_MAJOR_SUBJECTS = frozenset({
    _INTEGRATED_408,   # 计算机学科专业基础（含数据结构/操作系统/网络/软工）
    "数字电子技术",
    "模拟电子技术",
    "电路",
    "电路分析",
    "信号与系统",
    "通信原理",
    "光学",
    "普通物理",
    "网络补充",
    "真题综合",         # 混合真题集合的显式标签（非二级学科污染，保留）
    "408",            # `计算机学科专业基础408` 的常用简称（同一门课，非二级学科）
})

#: 跨门类统考科目（管综/经综/法硕/教育学/心理学/中西医综合）。
#: 它们是**独立招生学科口径**的叶子标签，不是任何学科的二级组成，所以进白名单；
#: 语料里已经存在这些文档（实测约占全库 8.4%），此前因为没有标签被塞进电子/数学池。
#: 权威名单见 `services/taxonomy.CROSS_SUBJECTS`，这里按同名叠加。
_CROSS_MAJOR_SUBJECTS = frozenset({
    "管理类联考综合",
    "经济类联考综合",
    "法律硕士专业基础",
    "教育学专业基础",
    "心理学专业基础",
    "西医综合",
    "中医综合",
})

#: 文档学科锁白名单：只允许叶子级真学科作为文档归属标签。
#: 显式**排除**：`数据结构`/`操作系统`/`计算机网络`/`软件工程`（408 二级学科）、
#: 一级学科名（`计算机科学与技术`/`电子信息`/`电气工程`/`控制科学与工程`/
#: `信息与通信工程`/`电子科学与技术`/`光学工程`/`光学与工程光学`/`计算机基础`）、
#: 以及 `其他`/`未知`/`未分类` 等兜底值（由 `_VACUOUS_SUBJECTS` 另行排除）。
DOC_LOCK_ALLOWLIST: FrozenSet[str] = (
    _PUBLIC_SUBJECTS | _MAJOR_SUBJECTS | _CROSS_MAJOR_SUBJECTS
)


def is_doc_lock_subject(name: str) -> bool:
    """`name` 是否可作为**文档归属学科标签**。

    Args:
        name: 待判定的学科标签（大小写/空白不敏感，仅去首尾空白）。

    Returns:
        True 表示该标签是叶子级真学科，可用于文档学科锁。
    """
    return (name or "").strip() in DOC_LOCK_ALLOWLIST