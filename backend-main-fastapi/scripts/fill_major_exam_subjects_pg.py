# 数学科目集合（用于去重：math 已单独加入时，exam 里不应再出现数学）
MATH_SUBJECTS = {MATH1, MATH2, MATH3, "(601)数学分析", "(701)高等数学", "(301)数学（一）", "(302)数学（二）", "(303)数学（三）"}


def get_exam_subjects(subject_code: str, major_name: str) -> list[str]:
    """根据 subject_code + 专业名 推导考试科目列表。"""
    cfg = SUBJECT_CODE_MAP.get(subject_code)
    if cfg is None:
        fallback = FALLBACK_MAP.get(subject_code)
        if fallback:
            return [PUBLIC_POLITICS, PUBLIC_ENGLISH] + fallback
        return [PUBLIC_POLITICS, PUBLIC_ENGLISH, f"({subject_code})专业综合"]

    exam = cfg.get("default_exam", [])
    # 按专业名精确匹配
    if major_name and "major_exam" in cfg:
        for pat, subs in cfg["major_exam"].items():
            if pat and pat in major_name:
                exam = subs
                break

    math = cfg.get("math")
    result = []
    if math:
        result = [PUBLIC_POLITICS, PUBLIC_ENGLISH, math]
    else:
        result = [PUBLIC_POLITICS, PUBLIC_ENGLISH]
    # 过滤掉 exam 中重复的数学科目（数学已由 math 字段加入）
    for item in exam:
        if item in MATH_SUBJECTS:
            continue
        result.append(item)
    return result


def get_reference_books(subject_code: str, major_name: str) -> list[str]:
    """根据 subject_code 推导参考书。"""
    cfg = SUBJECT_CODE_MAP.get(subject_code)
    if cfg is None:
        return [f"{major_name or subject_code} 权威教材"]
    return cfg.get("books", [f"{major_name or subject_code} 权威教材"])


def main() -> None:
    ap = argparse.ArgumentParser()
    ap.add_argument("--apply", action="store_true", help="写入数据库")
    ap.add_argument("--dry-run", action="store_true", help="只统计不写入")
    ap.add_argument("--rebuild-all", action="store_true", help="重建全部记录的 exam_subjects/reference_books")
    args = ap.parse_args()

    conn = psycopg.connect(**DB)
    cur = conn.cursor()

    # 读取需要填充的专业
    cur.execute(
        """
        SELECT id, name, code, subject_code, exam_subjects, reference_books
        FROM kaoyan_majors
        WHERE deleted_at IS NULL
        """
    )
    rows = cur.fetchall()

    to_update_exam = []
    to_update_books = []
    stats_exam = Counter()
    stats_books = Counter()

    for mid, name, code, subject_code, exam_subjects, reference_books in rows:
        subject_code = subject_code or (code[:4] if code and len(code) >= 4 else None)
        name = name or ""

        # 填充 exam_subjects：--rebuild-all 时全部重建；否则只填空
        need_exam = args.rebuild_all or not exam_subjects or len(exam_subjects) == 0
        if need_exam:
            new_exam = get_exam_subjects(subject_code, name)
            to_update_exam.append((Jsonb(new_exam), mid))
            stats_exam[subject_code or "UNKNOWN"] += 1

        # 填充 reference_books：--rebuild-all 时全部重建；否则只填空
        need_books = args.rebuild_all or not reference_books or len(reference_books) == 0
        if need_books:
            new_books = get_reference_books(subject_code, name)
            to_update_books.append((Jsonb(new_books), mid))
            stats_books[subject_code or "UNKNOWN"] += 1

    print(f"总专业: {len(rows)}")
    print(f"需填充 exam_subjects: {len(to_update_exam)}")
    print(f"需填充 reference_books: {len(to_update_books)}")
    print()
    print("=== exam_subjects 填充分布 TOP20 ===")
    for k, v in stats_exam.most_common(20):
        print(f"  {k}: {v}")

    if not args.apply:
        print("\n[dry-run] 未写入数据库。加 --apply 执行写入。")
        conn.close()
        return

    # 事务写入
    try:
        with conn.cursor() as cur2:
            cur2.executemany(
                "UPDATE kaoyan_majors SET exam_subjects = %s WHERE id = %s",
                to_update_exam,
            )
            print(f"已更新 exam_subjects: {cur2.rowcount}")
        with conn.cursor() as cur3:
            cur3.executemany(
                "UPDATE kaoyan_majors SET reference_books = %s WHERE id = %s",
                to_update_books,
            )
            print(f"已更新 reference_books: {cur3.rowcount}")
        conn.commit()
        print("提交成功！")
    except Exception as exc:
        conn.rollback()
        print(f"写入失败，已回滚: {exc}")
        raise
    finally:
        conn.close()


if __name__ == "__main__":
    main()