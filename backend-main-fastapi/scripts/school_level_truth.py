# ---------------------------------------------------------------- 归一化工具
_PAREN_MAP = {"（": "(", "）": ")", " ": "", " ": "", "　": ""}


def normalize_name(raw: str) -> str:
    """院校名归一（全角括号→ 半角、去空白），用于跨写法匹配。"""
    if not raw:
        return ""
    out = str(raw)
    for src, dst in _PAREN_MAP.items():
        out = out.replace(src, dst)
    return out.strip()


def canon(raw: str) -> str:
    """归一后统一为「全角括号」形态，作为权威名单的匹配键。"""
    return normalize_name(raw).replace("(", "（").replace(")", "）")


_C985 = {canon(x) for x in SET_985}
_C211 = {canon(x) for x in SET_211}
_CSYL = {canon(x) for x in SET_SHUANGYILIU}


def truth_level(raw_name: str):
    """返回权威 level（'985'/'211'/'双一流'）；不在任何名单内返回 None。"""
    n = canon(raw_name)
    if n in _C985:
        return "985"
    if n in _C211:
        return "211"
    if n in _CSYL:
        return "双一流"
    return None


def is_double_first_class(raw_name: str) -> bool:
    """是否确为双一流建设高校（含 985/211，双一流是更宽的集合）。"""
    return canon(raw_name) in (_C985 | _C211 | _CSYL)