/* 省份名 ↔ china.json 行政区全名。
   库里存短名（广东 / 内蒙古 / 广西），GeoJSON 用全名（广东省 / 内蒙古自治区 /
   广西壮族自治区）。ECharts map 按名字绑定数据，名字对不上就整张图不着色。 */
const SUFFIX = {
  北京: '市', 天津: '市', 上海: '市', 重庆: '市',
  河北: '省', 山西: '省', 辽宁: '省', 吉林: '省', 黑龙江: '省',
  江苏: '省', 浙江: '省', 安徽: '省', 福建: '省', 江西: '省', 山东: '省',
  河南: '省', 湖北: '省', 湖南: '省', 广东: '省', 海南: '省', 四川: '省',
  贵州: '省', 云南: '省', 陕西: '省', 甘肃: '省', 青海: '省', 台湾: '省',
  内蒙古: '自治区',
  广西: '壮族自治区',
  西藏: '自治区',
  宁夏: '回族自治区',
  新疆: '维吾尔自治区',
  香港: '特别行政区', 澳门: '特别行政区',
}

export function toEchartsProvince(name) {
  if (!name) return ''
  const v = String(name).trim()
  const short = v
    .replace(/(壮族|回族|维吾尔)?自治区$/, '')
    .replace(/(省|市|特别行政区)$/, '')
    .trim()
  if (v !== short && /(省|市|自治区|特别行政区)$/.test(v)) return v
  return SUFFIX[short] ? short + SUFFIX[short] : v
}
